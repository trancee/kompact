package ch.trancee.mutation

/**
 * Renders one MutFlow adapter class that wraps every `@Test` method of the given test sources in its
 * own `MutFlow.underTest` scope. One class scope lets every behavior test kill any mutant, and one
 * adapter method per behavior test keeps class-qualified killer identities and MutFlow's per-test
 * budget. Sources are parsed lexically; any `@Test` that is not a parameterless function fails
 * generation instead of being skipped.
 */
object MutationAdapterSource {
    private val packagePattern = Regex("""^package\s+([\w.]+)""", RegexOption.MULTILINE)
    private val topLevelTypePattern =
        Regex(
            """^(?:(?:public|internal|private|abstract|open|data|sealed)\s+)*(?:class|object)\s+(\w+)""",
            RegexOption.MULTILINE,
        )
    private val testAnnotationPattern = Regex("""@Test\b""")
    private val testFunctionPattern = Regex("""\G@Test\s+(?:@\w+(?:\([^)]*\))?\s+)*fun\s+(`[^`]+`|\w+)\s*\(\s*\)""")

    private data class TestMethod(
        val className: String,
        val simpleClassName: String,
        val methodName: String,
    ) {
        val adapterName: String = "$simpleClassName ${methodName.trim('`')}"
    }

    fun render(
        packageName: String,
        className: String,
        sources: List<String>,
    ): String {
        val methods = sources.flatMap(::testMethods).sortedBy { it.className }
        val duplicates = methods.groupBy { it.adapterName }.filterValues { it.size > 1 }.keys
        require(duplicates.isEmpty()) { "Duplicate mutation adapter methods: ${duplicates.sorted()}" }
        return buildString {
            appendLine("// Generated by the mutation-results plugin from the module's test sources. Do not edit.")
            appendLine("package $packageName")
            appendLine()
            appendLine("import io.github.anschnapp.mutflow.MutFlow")
            appendLine("import io.github.anschnapp.mutflow.junit.MutFlowTest")
            appendLine("import kotlin.test.Test")
            appendLine()
            appendLine("@MutFlowTest")
            appendLine("class $className {")
            methods.forEachIndexed { index, method ->
                if (index > 0) appendLine()
                appendLine("    @Test")
                appendLine("    fun `${method.adapterName}`() {")
                appendLine("        val tests = ${method.className}()")
                appendLine("        MutFlow.underTest { tests.${method.methodName}() }")
                appendLine("    }")
            }
            appendLine("}")
        }
    }

    private fun testMethods(source: String): List<TestMethod> {
        val packageName = packagePattern.find(source)?.groupValues?.get(1)
        val types = topLevelTypePattern.findAll(source).toList()
        return testAnnotationPattern
            .findAll(source)
            .map { annotation ->
                val owner = types.lastOrNull { it.range.first < annotation.range.first }?.groupValues?.get(1)
                val qualifiedOwner = listOfNotNull(packageName, owner).joinToString(".")
                val function = testFunctionPattern.find(source, annotation.range.first)
                require(owner != null && function != null) {
                    "Cannot wrap the @Test at offset ${annotation.range.first} in $qualifiedOwner; " +
                        "mutation adapters need parameterless test functions in a top-level class"
                }
                TestMethod(qualifiedOwner, owner, function.groupValues[1])
            }.toList()
    }
}
