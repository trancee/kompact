package ch.trancee.mutation

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertThrows
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

class MutationAdapterSourceTest {
    @Test
    fun `wraps every test method in its own MutFlow scope`() {
        val source =
            """
            package example.cursor

            import kotlin.test.Test

            class CursorTest {
                @Test
                fun readsBits() {
                    check(true)
                }

                @Test
                @Suppress("UNUSED_EXPRESSION")
                fun `rejects a negative width`() {
                }

                private fun helper() = Unit
            }
            """.trimIndent()

        val adapter = MutationAdapterSource.render("example", "ExampleMutationTest", listOf(source))

        assertEquals(
            """
            // Generated by the mutation-results plugin from the module's test sources. Do not edit.
            package example

            import io.github.anschnapp.mutflow.MutFlow
            import io.github.anschnapp.mutflow.junit.MutFlowTest
            import kotlin.test.Test

            @MutFlowTest
            class ExampleMutationTest {
                @Test
                fun `CursorTest readsBits`() {
                    val tests = example.cursor.CursorTest()
                    MutFlow.underTest { tests.readsBits() }
                }

                @Test
                fun `CursorTest rejects a negative width`() {
                    val tests = example.cursor.CursorTest()
                    MutFlow.underTest { tests.`rejects a negative width`() }
                }
            }

            """.trimIndent(),
            adapter,
        )
    }

    @Test
    fun `orders classes by qualified name and keeps declaration order within a class`() {
        val second =
            """
            package b

            class ZetaTest {
                @Test
                fun second() {}

                @Test
                fun first() {}
            }
            """.trimIndent()
        val first =
            """
            package a

            internal object Fixture

            class AlphaTest {
                @Test
                fun only() {}
            }
            """.trimIndent()

        val adapter = MutationAdapterSource.render("a", "AdapterTest", listOf(second, first))

        val calls = Regex("""tests = ([\w.]+)\(\)\s+MutFlow.underTest \{ tests.(\w+)\(\)""").findAll(adapter)
        assertEquals(
            listOf("a.AlphaTest.only", "b.ZetaTest.second", "b.ZetaTest.first"),
            calls.map { "${it.groupValues[1]}.${it.groupValues[2]}" }.toList(),
        )
    }

    @Test
    fun `sources without tests contribute nothing`() {
        val adapter = MutationAdapterSource.render("a", "AdapterTest", listOf("package a\n\nclass Helper"))

        assertTrue("@Test\n" !in adapter.substringAfter("class AdapterTest"))
    }

    @Test
    fun `a test that cannot be wrapped fails generation`() {
        val parameterized =
            """
            package a

            class BrokenTest {
                @Test
                fun withArgument(value: Int) {}
            }
            """.trimIndent()

        val failure =
            assertThrows(IllegalArgumentException::class.java) {
                MutationAdapterSource.render("a", "AdapterTest", listOf(parameterized))
            }

        assertTrue("a.BrokenTest" in failure.message.orEmpty())
    }

    @Test
    fun `duplicate adapter method names fail generation`() {
        val left = "package a\n\nclass SameTest {\n    @Test\n    fun x() {}\n}"
        val right = "package b\n\nclass SameTest {\n    @Test\n    fun x() {}\n}"

        val failure =
            assertThrows(IllegalArgumentException::class.java) {
                MutationAdapterSource.render("a", "AdapterTest", listOf(left, right))
            }

        assertTrue("SameTest x" in failure.message.orEmpty())
    }
}
